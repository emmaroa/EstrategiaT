const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const storage=new Map(),context={localStorage:{getItem:k=>storage.get(k),setItem:(k,v)=>storage.set(k,v)}};
vm.runInNewContext(fs.readFileSync('js/core/notifications-feed.js','utf8'),context);
const api=context.ETNotificationsFeed,user={id:'uno'},other={id:'dos'};
assert.equal(api.preferences(user).enabled,true);
const saved=api.savePreferences(user,{enabled:true,popups:false,categories:{cotizaciones:false,recordatorios:false}});
assert.equal(api.allows({tipo:'cambio_cotizaciones_almacen'},saved),false);
assert.equal(api.allows({tipo:'cotizacion_requisicion_generada'},saved),false);
assert.equal(api.allows({tipo:'calendario_recordatorio'},saved),false);
assert.equal(api.allows({tipo:'cambio_eventos_calendario'},saved),true);
assert.equal(api.allows({tipo:'acuerdo_asignado'},saved),true);
assert.equal(api.allows({tipo:'nuevo_tipo'},saved),true);
assert.equal(api.preferences(user).popups,false);
assert.equal(api.preferences(other).categories.cotizaciones,true,'Preferences are isolated by account');
assert.equal(api.allows({tipo:'calendario'},api.savePreferences(user,{enabled:false})),false);
assert.equal(api.allows({tipo:'cambio_peticiones'},api.savePreferences(user,{categories:Object.fromEntries(api.categories.map(([key])=>[key,false]))})),false);
storage.set('etNotificationPreferences:v1:uno','invalid');assert.equal(api.preferences(user).enabled,true);
context.localStorage.setItem=()=>{throw Error('quota')};assert.throws(()=>api.savePreferences(user,{}));
assert.throws(()=>api.savePreferences({},{}));
console.log('Preferencias: categorías, recordatorios, silencio general, emergentes, persistencia, cuentas y errores verificados.');
