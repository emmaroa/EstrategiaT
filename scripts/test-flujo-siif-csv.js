const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const ctx={};vm.runInNewContext(fs.readFileSync('js/services/flujo-siif-csv.js','utf8'),ctx);
const api=ctx.ETFlujoCSV;
const registros=[{id:'a',numero_req:'000123',fecha_req:'2026-01-01'},{id:'b',numero_req:'123',fecha_req:'2025-01-01'},{id:'c',numero_req:'456',fecha_req:'2026-01-01'}];
const rows=api.parse('\ufeffRequisición\r\n00123\r\n456\r\n456\r\n999\r\n');
assert.equal(api.encabezado(rows[0][0]),true);
let result=api.match(rows,registros,{header:true});
assert.equal(result.ids.join(','),'c');assert.match(result.detalles[0].estado,/Ambigua/);
result=api.match(rows,registros,{header:true,year:'2026'});
assert.equal(result.ids.join(','),'a,c');assert.equal(result.detalles[2].estado,'Repetida en CSV');assert.equal(result.detalles[3].estado,'No encontrada');
assert.equal(api.match(api.parse('123\n456'),registros,{year:'2026'}).ids.length,2);
const multi=api.parse('Nota;numero_req\n"Texto; con separador";123\n"Texto con\nsalto y ""comillas""";456');
assert.equal(multi[2][0],'Texto con\nsalto y "comillas"');assert.equal(api.match(multi,registros,{header:true,columna:1,year:'2026'}).ids.length,2);
assert.equal(api.parse('REQ\tNota\n123\tHola')[1][0],'123');
assert.throws(()=>api.parse('"123'));assert.throws(()=>api.parse('"123"error'));assert.throws(()=>api.parse(''));
assert.throws(()=>api.parse('x'.repeat(1024*1024+1)));
assert.throws(()=>api.parse('REQ\n'+Array.from({length:5001},(_,i)=>i).join('\n')));
assert.equal(api.match(api.parse('REQ\n=1+1\n<img src=x>'),registros,{header:true}).ids.length,0);
console.log('CSV seguimiento: encabezados, delimitadores, comillas, ceros, años ambiguos, duplicados, no encontrados y límites verificados.');
